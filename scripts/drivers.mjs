// -----------------------------------------------------------------------------
// Regenerates src/drivers.js: for each wmbusmeters driver (and alias), its
// manufacturer and the alarm families (leak, burst, dry, backflow, tamper,
// battery) its status flags can raise, so the alarm features are offered in
// Discovery before the first alarm.
//
// Input: the driver definitions of a wmbusmeters checkout converted to JSON
// with the `xmq` tool of the official image (one driver per line):
//
//   docker run --rm -v $PWD/drivers/src:/d:ro --entrypoint sh \
//     wmbusmeters/wmbusmeters:latest -c 'apk add -q libxslt; \
//     for f in /d/*.xmq; do xmq $f to-json; echo; done' > drivers.jsonl
//   node scripts/drivers.mjs drivers.jsonl <wmbusmeters commit>
//   npm run format
//
// Only facts are kept (names, manufacturers, flag families): no code nor text
// of the GPL definitions.
// -----------------------------------------------------------------------------

import { readFileSync, writeFileSync } from 'node:fs';
import { STATUS_FIELDS, familiesOf } from '../src/mapping.js';

const [input, commit = 'unknown'] = process.argv.slice(2);
if (!input) {
  console.error('Usage: node scripts/drivers.mjs <drivers.jsonl> [wmbusmeters commit]');
  process.exit(1);
}

/** The entries of an xmq list: {"field[0]": a, "field[1]": b} or {"field": a}. */
const entries = (node, name) =>
  node && typeof node === 'object'
    ? Object.entries(node)
        .filter(([k]) => k === name || k.startsWith(`${name}[`))
        .map(([, v]) => v)
    : [];

/** The flag names of the lookups of a field (and of its template). */
function lookupNames(field, templates) {
  const lookups = [...entries(field, 'lookup')];
  const template = templates.find((t) => t.name === field.template);
  if (template) {
    lookups.push(...entries(template, 'lookup'));
  }
  return lookups.flatMap((l) => entries(l, 'map').map((m) => String(m.name ?? '')));
}

/** Hand-written: the drivers written in C++ (src/driver_*.cc), not in the xmq definitions. */
const NATIVE = {
  izar: { manufacturer: 'Diehl', alarms: ['backflow', 'leak', 'tamper'] },
  hydroclima: { manufacturer: 'BMeters' },
  qheat: { manufacturer: 'Qundis' },
  qwater: { manufacturer: 'Qundis' },
};

const isStatus = (f) =>
  STATUS_FIELDS.includes(f.name) ||
  /(?:^|,)(?:STATUS|INJECT_INTO_STATUS)(?:,|$)/.test(String(f.attributes ?? ''));

const drivers = { ...NATIVE };
for (const line of readFileSync(input, 'utf8').split('\n')) {
  if (!line.trim().startsWith('{')) {
    continue;
  }
  const d = JSON.parse(line);
  const templates = entries(d.templates, 'template_field');
  const fields = entries(d.fields, 'field');
  const words = fields
    .filter(isStatus)
    .flatMap((f) => lookupNames(f, templates))
    .map((w) => w.toUpperCase());
  const alarms = familiesOf(words);
  if (fields.some((f) => f.name === 'status' && /INCLUDE_TPL_STATUS/.test(String(f.attributes)))) {
    alarms.add('battery'); // the transport layer status: POWER_LOW
  }
  const entry = {};
  if (typeof d.manufacturer === 'string' && d.manufacturer.trim()) {
    entry.manufacturer = d.manufacturer.trim();
  }
  if (alarms.size > 0) {
    entry.alarms = [...alarms].sort();
  }
  for (const name of [d.name, ...String(d.aliases ?? '').split(',')]) {
    if (name && name.trim()) {
      drivers[name.trim()] = entry;
    }
  }
}

const sorted = Object.entries(drivers).sort(([a], [b]) => a.localeCompare(b));
const body = sorted
  .map(
    ([name, e]) =>
      `  ${/^[a-z_][a-z0-9_]*$/.test(name) ? name : `'${name}'`}: ${JSON.stringify(e)},`,
  )
  .join('\n');
writeFileSync(
  new URL('../src/drivers.js', import.meta.url),
  `// -----------------------------------------------------------------------------
// GENERATED by scripts/drivers.mjs from the wmbusmeters driver definitions
// (github.com/wmbusmeters/wmbusmeters, commit ${commit}). Facts only: the
// driver names, their manufacturer and the alarm families their status flags
// can raise. Do not edit by hand: regenerate.
// -----------------------------------------------------------------------------

/** driver -> { manufacturer?, alarms? } */
export const DRIVERS = {
${body}
};
`,
);
console.log(`${sorted.length} drivers written to src/drivers.js`);
